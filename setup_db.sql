-- 6. ReminderLog (SMS / e-mail history behind the reminder panel) ------------
-- AppointmentId 0 = a whole-day e-mail digest, so there is deliberately no
-- foreign key here (same behaviour as the original SQL Server schema).
CREATE TABLE IF NOT EXISTS "ReminderLog" (
    "Id"            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AppointmentId" INTEGER NOT NULL,
    "Channel"       VARCHAR(20) NOT NULL,
    "Destination"   VARCHAR(200) NOT NULL,
    "Message"       TEXT NOT NULL,
    "Status"        VARCHAR(20) NOT NULL,
    "Error"         TEXT NULL,
    "SentAt"        TIMESTAMP NOT NULL DEFAULT NOW()
);

