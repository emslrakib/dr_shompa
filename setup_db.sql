-- ============================================================================
--  DrShompa — PostgreSQL schema + sample data
--
--  চালান / Run it with:
--      npm.cmd run db:migrate
--  (টেবিল + sample data একবারেই তৈরি হয়; বারবার চালালেও কিছু নষ্ট হয় না)
--
--  The script is idempotent: running it again never duplicates a row and never
--  drops data. server.js also runs it automatically at startup
--  (switch that off with DB_AUTO_MIGRATE=false).
--
--  Table and column names are quoted on purpose, so PostgreSQL keeps the exact
--  casing the API and the frontend already use ("PatientName", "PreferredDate",
--  ...). Never recreate these tables with unquoted names — PostgreSQL would
--  fold them to lower case and every API response would suddenly use
--  different field names.
-- ============================================================================

-- 1. Appointments ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "Appointments" (
    "Id"            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PatientName"   VARCHAR(150) NOT NULL,
    "Age"           INTEGER NOT NULL,
    "Phone"         VARCHAR(30) NOT NULL,
    "VisitType"     VARCHAR(50) NOT NULL,
    "PreferredDate" DATE NOT NULL,
    "PreferredSlot" VARCHAR(50) NOT NULL,
    "Notes"         TEXT NULL,
    "Status"        VARCHAR(30) NOT NULL DEFAULT 'Pending',
    "CreatedAt"     TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Index used by the protected appointment dashboard and the reminder queries.
CREATE INDEX IF NOT EXISTS "IX_Appointments_PreferredDate_Status"
    ON "Appointments" ("PreferredDate", "Status")
    INCLUDE ("CreatedAt", "PatientName", "Phone", "PreferredSlot");

